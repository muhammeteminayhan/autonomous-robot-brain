#!/usr/bin/env python3
"""Collect every scenario's metrics into the Phase 10 comparison table.

Reads results/phase10/metrics_case_*.json -- whatever is there -- and writes a
Markdown table and a summary chart. Separate from run_scenario.py on purpose:
re-deriving the table is instant, while re-running the six scenarios is
fifteen minutes of simulation, and a table that can only be regenerated by
re-running the experiment cannot be corrected.

Usage::

    python3 scripts/fault_report.py
    python3 scripts/fault_report.py --estimator odometry
"""

from __future__ import annotations

import argparse
import json
import pathlib

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402

REPO_ROOT = pathlib.Path(__file__).resolve().parents[1]

#: Display order and short label. Sorting by filename would put the cases in
#: alphabetical order, which happens to be right here and would silently stop
#: being right the moment a case is renamed.
CASES = [
    ("case_a_nominal", "A", "Nominal"),
    ("case_b_imu_high_noise", "B", "IMU noise x10"),
    ("case_c_encoder_drift", "C", "Encoder drift"),
    ("case_d_lidar_dropout", "D", "LiDAR dropout 60 %"),
    ("case_e_sensor_outage", "E", "Sensor outage 10 s"),
    ("case_f_multi_degradation", "F", "Multi-degradation"),
]


def fmt(value, spec: str = ".4f", dash: str = "--") -> str:
    if value is None:
        return dash
    try:
        f = float(value)
    except (TypeError, ValueError):
        return str(value)
    return dash if not np.isfinite(f) else format(f, spec)


def load(results_dir: pathlib.Path) -> dict:
    out = {}
    for case_id, _, _ in CASES:
        path = results_dir / f"metrics_{case_id}.json"
        if path.exists():
            out[case_id] = json.loads(path.read_text())
    return out


def table(data: dict, estimator: str) -> str:
    baseline = data.get("case_a_nominal", {}).get(
        "estimators", {}).get(estimator, {})
    base_pos = baseline.get("position_rmse_m")
    base_head = baseline.get("heading_rmse_deg")

    lines = [
        f"| Case | Scenario | Position RMSE [m] | vs A | Heading RMSE [deg] "
        f"| vs A | Degraded-phase pos. RMSE [m] | Recovery [s] | Inside 2-sigma |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for case_id, letter, label in CASES:
        entry = data.get(case_id)
        if entry is None:
            lines.append(f"| {letter} | {label} | *not run* | | | | | | |")
            continue
        m = entry["estimators"].get(estimator, {})
        pos, head = m.get("position_rmse_m"), m.get("heading_rmse_deg")
        ratio_p = (f"{pos / base_pos:.2f}x"
                   if base_pos and pos and np.isfinite(pos) else "--")
        ratio_h = (f"{head / base_head:.2f}x"
                   if base_head and head and np.isfinite(head) else "--")
        # "no fault" and "did not recover" both have no number, and collapsing
        # them to a dash would hide a filter that never came back.
        outcome = m.get("recovery_outcome", "")
        rec = m.get("recovery_time_s")
        if outcome in ("no fault", "no post-fault window"):
            rec_text = "n/a"
        elif outcome == "did not recover":
            rec_text = "**never**"
        else:
            rec_text = fmt(rec, ".1f")
        inside = m.get("fraction_inside_2sigma_pos")
        lines.append(
            f"| {letter} | {label} | {fmt(pos)} | {ratio_p} | {fmt(head, '.2f')} "
            f"| {ratio_h} | {fmt(m.get('position_rmse_degraded_m'))} | {rec_text} "
            f"| {fmt(inside and inside * 100, '.0f')} % |")
    return "\n".join(lines)


def chart(data: dict, out_dir: pathlib.Path) -> pathlib.Path:
    letters, pos_o, pos_e, head_o, head_e = [], [], [], [], []
    for case_id, letter, _ in CASES:
        entry = data.get(case_id)
        if entry is None:
            continue
        letters.append(letter)
        est = entry["estimators"]
        pos_o.append(est.get("odometry", {}).get("position_rmse_m", np.nan))
        pos_e.append(est.get("ekf", {}).get("position_rmse_m", np.nan))
        head_o.append(est.get("odometry", {}).get("heading_rmse_deg", np.nan))
        head_e.append(est.get("ekf", {}).get("heading_rmse_deg", np.nan))

    x = np.arange(len(letters))
    fig, axes = plt.subplots(1, 2, figsize=(12, 4.5))
    for ax, (o, e, label) in zip(axes, [
            (pos_o, pos_e, "position RMSE [m]"),
            (head_o, head_e, "heading RMSE [deg]")]):
        ax.bar(x - 0.2, o, 0.4, color="#e03131", label="wheel odometry")
        ax.bar(x + 0.2, e, 0.4, color="#1971c2", label="EKF")
        ax.set_xticks(x)
        ax.set_xticklabels(letters)
        ax.set_ylabel(label)
        ax.grid(alpha=0.25, axis="y")
        ax.legend(fontsize=8)
    axes[0].set_title("Phase 10 -- estimator error per fault scenario")
    axes[1].set_title("Lower is better; A is the healthy baseline")
    path = out_dir / "fault_comparison.png"
    fig.tight_layout()
    fig.savefig(path, dpi=140)
    plt.close(fig)
    return path


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--results", default=None)
    ap.add_argument("--estimator", default="ekf", choices=["ekf", "odometry"])
    args = ap.parse_args(argv)

    results_dir = (pathlib.Path(args.results) if args.results
                   else REPO_ROOT / "results" / "phase10")
    data = load(results_dir)
    if not data:
        print(f"no metrics found in {results_dir}")
        return 1

    missing = [c for c, _, _ in CASES if c not in data]
    for estimator in ("ekf", "odometry"):
        print(f"\n### {estimator}\n")
        print(table(data, estimator))
    path = chart(data, results_dir)
    print(f"\nwrote {path}")
    if missing:
        print(f"NOT RUN: {', '.join(missing)}")

    with open(results_dir / "summary.md", "w") as fh:
        fh.write("# Phase 10 -- fault injection results\n\n")
        for estimator in ("ekf", "odometry"):
            fh.write(f"## {estimator}\n\n{table(data, estimator)}\n\n")
        if missing:
            fh.write(f"Not run: {', '.join(missing)}\n")
    print(f"wrote {results_dir}/summary.md")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
